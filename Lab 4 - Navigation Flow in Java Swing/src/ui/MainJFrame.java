    private void showPanel(JPanel panel) {
        bottomPanel.removeAll();
        bottomPanel.add(panel);
        CardLayout layout = (CardLayout) bottomPanel.getLayout();
        layout.next(bottomPanel);
        bottomPanel.revalidate();
        bottomPanel.repaint();
    }

