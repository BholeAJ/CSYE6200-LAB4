    private void uploadPhotoButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_uploadPhotoButtonActionPerformed
        JFileChooser chooser = new JFileChooser();
        chooser.setFileFilter(new FileNameExtensionFilter("Images (jpg, jpeg, png, gif)", "jpg", "jpeg", "png", "gif"));
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        File file = chooser.getSelectedFile();
        try {
            BufferedImage image = ImageIO.read(file);
            if (image == null) {
                showError("The selected file is not a valid image.", uploadPhotoButton);
                return;
            }
            picture = new ImageIcon(scaleToFit(image));
            imageLabel.setIcon(picture);
            photoTextField.setText(file.getAbsolutePath());
        } catch (IOException e) {
            showError("Could not read the selected image.", uploadPhotoButton);
        }
    }//GEN-LAST:event_uploadPhotoButtonActionPerformed

    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitButtonActionPerformed
        if (!isFormValid()) {
            return;
        }

        User user = new User();
        user.setFirstName(firstNameTextField.getText().trim());
        user.setLastName(lastNameTextField.getText().trim());
        user.setDateOfBirth(dobDateChooser.getDate());
        user.setAge(calculateAge(dobDateChooser.getDate()));
        user.setGender(genderComboBox.getSelectedItem().toString());
        user.setEmail(emailTextField.getText().trim());
        user.setPhone(phoneFormattedTextField.getText());
        user.setContinent(continentComboBox.getSelectedItem().toString());
        user.setExperience(experienceTextArea.getText().trim());
        user.setPhotoPath(photoTextField.getText());
        user.setPicture(picture);

        JOptionPane.showMessageDialog(this, user.toString(), "Success!", JOptionPane.INFORMATION_MESSAGE, picture);

        if (mainFrame != null) {
            mainFrame.setUser(user);
        }
        if (bottomPanel != null) {
            bottomPanel.removeAll();
            bottomPanel.add(new ViewJPanel(user));
            CardLayout layout = (CardLayout) bottomPanel.getLayout();
            layout.next(bottomPanel);
            bottomPanel.revalidate();
            bottomPanel.repaint();
        }
    }//GEN-LAST:event_submitButtonActionPerformed

    private boolean isFormValid() {
        String firstName = firstNameTextField.getText().trim();
        if (firstName.isEmpty()) {
            return showError("Please enter your first name.", firstNameTextField);
        }
        if (!firstName.matches("[A-Za-z][A-Za-z '-]*")) {
            return showError("First name can only contain letters.", firstNameTextField);
        }

        String lastName = lastNameTextField.getText().trim();
        if (lastName.isEmpty()) {
            return showError("Please enter your last name.", lastNameTextField);
        }
        if (!lastName.matches("[A-Za-z][A-Za-z '-]*")) {
            return showError("Last name can only contain letters.", lastNameTextField);
        }

        Date dob = dobDateChooser.getDate();
        if (dob == null) {
            return showError("Please select your date of birth.", dobDateChooser);
        }
        if (toLocalDate(dob).isAfter(LocalDate.now())) {
            return showError("Date of birth cannot be in the future.", dobDateChooser);
        }
        if (calculateAge(dob) > 120) {
            return showError("Please select a valid date of birth.", dobDateChooser);
        }

        if (genderComboBox.getSelectedItem() == null) {
            return showError("Please select your gender.", genderComboBox);
        }

        String email = emailTextField.getText().trim();
        if (email.isEmpty()) {
            return showError("Please enter your email.", emailTextField);
        }
        if (!email.matches("^[\\w.+-]+@[\\w-]+(\\.[\\w-]+)*\\.[A-Za-z]{2,}$")) {
            return showError("Please enter a valid email (e.g. name@example.com).", emailTextField);
        }

        if (!phoneFormattedTextField.getText().matches("\\d{3}-\\d{3}-\\d{4}")) {
            return showError("Please enter a 10-digit phone number (123-456-7890).", phoneFormattedTextField);
        }

        if (continentComboBox.getSelectedItem() == null) {
            return showError("Please select your continent.", continentComboBox);
        }

        if (experienceTextArea.getText().trim().isEmpty()) {
            return showError("Please enter your experience.", experienceTextArea);
        }

        if (picture == null) {
            return showError("Please upload a photo.", uploadPhotoButton);
        }
        return true;
    }

    private LocalDate toLocalDate(Date date) {
        return date.toInstant().atZone(ZoneId.systemDefault()).toLocalDate();
    }

    private int calculateAge(Date dob) {
        return Period.between(toLocalDate(dob), LocalDate.now()).getYears();
    }

    private boolean showError(String message, JComponent field) {
        JOptionPane.showMessageDialog(this, message, "Oops!", JOptionPane.ERROR_MESSAGE);
        field.requestFocusInWindow();
        return false;
    }

    private Image scaleToFit(BufferedImage image) {
        double scale = Math.min((double) PHOTO_SIZE / image.getWidth(), (double) PHOTO_SIZE / image.getHeight());
        int width = Math.max(1, (int) (image.getWidth() * scale));
        int height = Math.max(1, (int) (image.getHeight() * scale));
        return image.getScaledInstance(width, height, Image.SCALE_SMOOTH);
    }

